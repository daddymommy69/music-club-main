"use client";

import { useState } from "react";
import type { siteCopy } from "@/lib/copy";

type SiteCopy = typeof siteCopy;

/**
 * Human labels + helper text for each editable field, in the order
 * they should appear in the form. Keyed off SiteCopy so TypeScript
 * catches it if src/lib/copy.ts ever gains/loses a field without this
 * list being updated to match (2026-10-18).
 */
const FIELDS: { key: keyof SiteCopy; label: string; hint?: string }[] = [
  {
    key: "homeIntro",
    label: "Home page intro",
    hint: "Shown at the very top of the home/releases page, above the drop list.",
  },
  {
    key: "tagline",
    label: "Site tagline",
    hint: "Shown under the wordmark in the header, and as a fallback page description.",
  },
  {
    key: "footerSignature",
    label: "Footer signature",
    hint: "Bottom-right of every page.",
  },
  {
    key: "dropBlurbPlaceholder",
    label: "Blurb placeholder — about a drop",
    hint: "Shown (grayed out) in the empty \"About this drop\" box in curator tools, before anyone's written anything.",
  },
  {
    key: "songBlurbPlaceholder",
    label: "Blurb placeholder — about a song",
    hint: "Same, for each song's own blurb box.",
  },
];

/**
 * Builds the literal source text of an updated src/lib/copy.ts from
 * whatever's currently in the form (2026-10-18). JSON.stringify gives
 * every value a safely-escaped double-quoted string literal — handles
 * quotes, newlines, backslashes, anything typed — without needing to
 * preserve the original file's exact formatting. Field order always
 * matches FIELDS above, not whatever order React state happens to
 * iterate in, so re-downloads stay stable to diff.
 */
function buildCopyFileText(values: Record<string, string>): string {
  const lines = FIELDS.map(({ key }) => `  ${key}: ${JSON.stringify(values[key] ?? "")},`).join("\n");
  return `/**\n * Centralized site copy — generated by the admin copy editor\n * (/admin/copy). Edit through that page, not by hand, so the two\n * never drift: download the updated file there and drop it into\n * your next GitHub upload at this exact path (src/lib/copy.ts).\n */\nexport const siteCopy = {\n${lines}\n};\n\nexport type SiteCopyKey = keyof typeof siteCopy;\n`;
}

export default function CopyEditorForm({ initial }: { initial: SiteCopy }) {
  const [values, setValues] = useState<Record<string, string>>(initial);
  const [downloaded, setDownloaded] = useState(false);

  function download() {
    const text = buildCopyFileText(values);
    const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "copy.ts";
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    setDownloaded(true);
  }

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 24 }}>
      {FIELDS.map(({ key, label, hint }) => (
        <div key={key}>
          <p className="label" style={{ marginBottom: 4 }}>
            {label}
          </p>
          {hint && (
            <p className="mut" style={{ fontSize: 11, marginBottom: 8 }}>
              {hint}
            </p>
          )}
          <textarea
            className="settings-input"
            style={{ resize: "vertical", padding: "10px 12px", lineHeight: 1.6, minHeight: 60 }}
            value={values[key] ?? ""}
            onChange={(e) => {
              setValues((v) => ({ ...v, [key]: e.target.value }));
              setDownloaded(false);
            }}
          />
        </div>
      ))}

      <div>
        <button type="button" className="btn btn-primary" onClick={download}>
          Download updated copy.ts
        </button>
        {downloaded && (
          <p className="mut" style={{ fontSize: 11.5, marginTop: 8, lineHeight: 1.6 }}>
            Downloaded. Drop it into your next upload at <code>src/lib/copy.ts</code> — same spot as the
            current one — to make these changes live.
          </p>
        )}
      </div>
    </div>
  );
}
